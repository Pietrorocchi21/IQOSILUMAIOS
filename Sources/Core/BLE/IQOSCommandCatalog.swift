import Foundation

enum IQOSCommandCatalog {
    static let loadBrightness: [UInt8] = [0x00, 0xC0, 0x02, 0x23, 0xC3]

    static let setBrightnessHigh: [[UInt8]] = [
        [0x00, 0xC0, 0x46, 0x23, 0x64, 0x00, 0x00, 0x00, 0x4F],
        [0x00, 0xC0, 0x02, 0x23, 0xC3],
        [0x00, 0xC9, 0x44, 0x24, 0x64, 0x00, 0x00, 0x00, 0x34]
    ]

    static let setBrightnessLow: [[UInt8]] = [
        [0x00, 0xC0, 0x46, 0x23, 0x1E, 0x00, 0x00, 0x00, 0xE1],
        [0x00, 0xC0, 0x02, 0x23, 0xC3],
        [0x00, 0xC9, 0x44, 0x24, 0x1E, 0x00, 0x00, 0x00, 0x9A]
    ]

    static func brightnessSequence(_ level: BrightnessLevel) -> [[UInt8]] {
        switch level {
        case .high:
            return setBrightnessHigh
        case .low:
            return setBrightnessLow
        }
    }

    static let lockSequence: [[UInt8]] = [
        [0x00, 0xC9, 0x44, 0x04, 0x02, 0xFF, 0x00, 0x00, 0x5A],
        [0x00, 0xC9, 0x00, 0x04, 0x1C],
        [0x00, 0xC0, 0x01, 0x00, 0xF6]
    ]

    static let unlockSequence: [[UInt8]] = [
        [0x00, 0xC9, 0x44, 0x04, 0x00, 0x00, 0x00, 0x00, 0x5D],
        [0x00, 0xC9, 0x00, 0x04, 0x1C],
        [0x00, 0xC0, 0x01, 0x00, 0xF6]
    ]

    static let loadAutostart: [UInt8] = [0x00, 0xC9, 0x07, 0x24, 0x01, 0x00, 0x00, 0x00, 0x22]
    static let autostartOn: [UInt8] = [0x00, 0xC9, 0x47, 0x24, 0x01, 0x01, 0x00, 0x00, 0x3F]
    static let autostartOff: [UInt8] = [0x00, 0xC9, 0x47, 0x24, 0x01, 0x00, 0x00, 0x00, 0x54]

    static func autostart(_ enabled: Bool) -> [UInt8] {
        enabled ? autostartOn : autostartOff
    }

    static let smartGestureOn: [UInt8] = [0x00, 0xC9, 0x47, 0x24, 0x04, 0x01, 0x00, 0x00, 0x3C]
    static let smartGestureOff: [UInt8] = [0x00, 0xC9, 0x47, 0x24, 0x04, 0x00, 0x00, 0x00, 0x57]

    static func smartGesture(_ enabled: Bool) -> [UInt8] {
        enabled ? smartGestureOn : smartGestureOff
    }

    static let loadVibrationSettings: [UInt8] = [0x00, 0xC9, 0x00, 0x23, 0xE9]
    static let startLocateVibration: [UInt8] = [0x00, 0xC0, 0x45, 0x22, 0x01, 0x1E, 0x00, 0x00, 0xC3]
    static let stopLocateVibration: [UInt8] = [0x00, 0xC0, 0x45, 0x22, 0x00, 0x1E, 0x00, 0x00, 0xD5]

    static let loadProductNumber: [UInt8] = [0x00, 0xC0, 0x00, 0x03, 0x09]
    static let loadFirmwareVersion: [UInt8] = [0x00, 0xC0, 0x00, 0x00, 0x00, 0x00, 0x00]

    static let loadTelemetry: [UInt8] = [0x00, 0xC9, 0x10, 0x02, 0x01, 0x01, 0x75, 0xD6]
    static let loadTimestamp: [UInt8] = [0x00, 0xC0, 0x10, 0x02, 0x00, 0x04, 0x38, 0xEF]
    static let loadBatteryVoltage: [UInt8] = [0x00, 0xC0, 0x00, 0x21, 0xE7]

    static let diagnosticSequence: [[UInt8]] = [
        loadTelemetry,
        loadTimestamp,
        loadTelemetry,
        loadBatteryVoltage
    ]

    static func vibrationUpdate(settings: VibrationSettings) -> [UInt8] {
        let heatingStartFlag: UInt16 = 0x0100
        let startingToUseFlag: UInt16 = 0x1000
        let puffEndFlag: UInt16 = 0x0001
        let manuallyTerminatedFlag: UInt16 = 0x0010

        var register: UInt16 = 0
        if settings.heatingStart {
            register |= heatingStartFlag
        }
        if settings.startingToUse {
            register |= startingToUseFlag
        }
        if settings.puffEnd {
            register |= puffEndFlag
        }
        if settings.manuallyTerminated {
            register |= manuallyTerminatedFlag
        }

        var checksum: UInt8 = 0x77
        if (register & puffEndFlag) != 0 {
            checksum ^= 0x07
        }
        if (register & manuallyTerminatedFlag) != 0 {
            checksum ^= 0x70
        }
        if (register & heatingStartFlag) != 0 {
            checksum ^= 0x15
        }
        if (register & startingToUseFlag) != 0 {
            checksum ^= 0x57
        }

        return [
            0x00, 0xC9, 0x44, 0x23, 0x10, 0x00,
            UInt8((register >> 8) & 0xFF),
            UInt8(register & 0xFF),
            checksum
        ]
    }
}
